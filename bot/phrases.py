def p(key: str, **kwargs: Any) -> str:
    """
    Вернуть случайную фразу по ключу, подставив переменные через str.format().

    Пример:
        p("workout_start_regular", name="Саня", day_key="A", workout_count=12)
    """
    variants = _PHRASES.get(key)
    if not variants:
        return f"[phrase not found: {key}]"
    template = random.choice(variants)
    try:
        return template.format(**kwargs)
    except KeyError as e:
        # Лучше вернуть сырой шаблон, чем падать в продакшне
        return template


def p_all(key: str) -> list[str]:
    """Вернуть все варианты фраз по ключу (для тестов)."""
    return _PHRASES.get(key, [])


def keys() -> list[str]:
    """Список всех доступных ключей."""
    return list(_PHRASES.keys())